let activeCustomCars: CarSpec[] = [];
let activeCarOverrides: Record<string, CarSpec> = {};

export function syncCustomCars(
  customCars: CarSpec[],
  carOverrides: Record<string, CarSpec> = activeCarOverrides
) {
  activeCustomCars = customCars;
  activeCarOverrides = carOverrides;
  const effectiveBase = BASE_CAR_CATALOG.map((c) => carOverrides[c.id] ?? c);
  const effectiveCustom = customCars.map((c) => carOverrides[c.id] ?? c);
  CAR_CATALOG.length = 0;
  CAR_CATALOG.push(...effectiveBase, ...effectiveCustom);
  for (const key of Object.keys(CAR_BY_ID)) {
    delete CAR_BY_ID[key];
  }
  for (const car of CAR_CATALOG) {
    CAR_BY_ID[car.id] = car;
  }
}

export function getCustomCarsSnapshot(): CarSpec[] {
  return activeCustomCars;
}

export const MAX_BRANCH_LEVEL = 9;
export const MAX_TOTAL_UPGRADES = 24;

export function getUpgradeCost(car: CarSpec, currentLevel: number): number {
  const rarityFactor: Record<RarityTier, number> = {
    Common: 120,
    Uncommon: 220,
    Rare: 400,
    'Super Rare': 700,
    'Ultra Rare': 1250,
    Epic: 2200,
    Legendary: 3800,
  };
  return Math.round(rarityFactor[car.rarity] * (1 + currentLevel * 0.28));
}

export function getSpentUpgradeCash(car: CarSpec, tuning: TuningLevels): number {
  let spent = 0;
  const levels = [
    Math.max(0, Math.min(MAX_BRANCH_LEVEL, tuning.engineLvl)),
    Math.max(0, Math.min(MAX_BRANCH_LEVEL, tuning.weightLvl)),
    Math.max(0, Math.min(MAX_BRANCH_LEVEL, tuning.chassisLvl)),
  ];
  for (const branchLvl of levels) {
    for (let lvl = 0; lvl < branchLvl; lvl++) {
      spent += getUpgradeCost(car, lvl);
    }
  }
  return spent;
}

export function getCarSellValue(car: CarSpec, tuning: TuningLevels): number {
  const baseValue: Record<RarityTier, number> = {
    Common: 350,
    Uncommon: 750,
    Rare: 1600,
    'Super Rare': 3400,
    'Ultra Rare': 7200,
    Epic: 15000,
    Legendary: 42000,
  };
  const spentCash = getSpentUpgradeCash(car, tuning);
  return Math.round(baseValue[car.rarity] + spentCash * 0.8);
}

export function computeEffectiveCarStats(
  car: CarSpec,
  tuning: TuningLevels = { engineLvl: 0, weightLvl: 0, chassisLvl: 0 }
): EffectiveCarStats {
  const e = Math.max(0, Math.min(MAX_BRANCH_LEVEL, tuning.engineLvl));
  const w = Math.max(0, Math.min(MAX_BRANCH_LEVEL, tuning.weightLvl));
  const c = Math.max(0, Math.min(MAX_BRANCH_LEVEL, tuning.chassisLvl));

  // Realistic modest upgrade curve (24/24 upgrades = ~+3.8% top speed, ~-9% 0-100, ~+5-6 handling)
  const topSpeedMph = Number((car.topSpeedMph * (1 + e * 0.0042 + w * 0.0008)).toFixed(1));
  const accelFactor = 1 - e * 0.0055 - w * 0.0045;
  const accel0to60 = Number(Math.max(1.6, car.accel0to60 * accelFactor).toFixed(2));
  const handling = Math.round(car.handling + c * 0.55 + w * 0.15);
  const mra = Number((car.mra + e * 0.35 + w * 0.1).toFixed(1));
  const weightLbs = Math.round(car.weightLbs * (1 - w * 0.007));
  const ola = Number((car.ola + e * 0.003 + w * 0.004 + c * 0.002).toFixed(3));

  const stageE = Math.ceil(e / 3);
  const stageW = Math.ceil(w / 3);
  const stageC = Math.ceil(c / 3);
  const buildCode = `${e}/${w}/${c} (${stageE}${stageW}${stageC})`;

  return {
    topSpeedMph,
    accel0to60,
    handling,
    mra,
    weightLbs,
    ola,
    totalUpgrades: e + w + c,
    buildCode,
  };
}

export function formatSpeed(mph: number, _settings?: PlayerSettings): string {
  return `${Math.round(mph * 1.60934)} km/h`;
}

export function formatWeight(lbs: number, _settings?: PlayerSettings): string {
  return `${Math.round(lbs * 0.453592).toLocaleString('sk-SK')} kg`;
}

export function formatAccel0to100(accel0to60: number, decimals = 2): string {
  return `${(accel0to60 * 1.038).toFixed(decimals)}s`;
}
